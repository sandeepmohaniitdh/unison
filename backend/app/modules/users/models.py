from datetime import datetime

from sqlalchemy import Boolean, Computed, ForeignKey, Index, String
from sqlalchemy.orm import Mapped, mapped_column

from app.core.time import utcnow
from app.core.types import ID, TIMESTAMP, enum
from app.db import Base

ROLES = ("student", "teacher", "admin")
USER_STATUSES = ("active", "suspended", "deactivated", "deleted")


class User(Base):
    """Every account. The email addresses live in user_emails."""

    __tablename__ = "users"

    id: Mapped[int] = mapped_column(ID, primary_key=True)
    name: Mapped[str] = mapped_column(String(120))
    role: Mapped[str] = mapped_column(enum("user_role", *ROLES))
    status: Mapped[str] = mapped_column(enum("user_status", *USER_STATUSES), default="active")
    password_hash: Mapped[str | None] = mapped_column(String(255))
    must_change_password: Mapped[bool] = mapped_column(Boolean, default=False)
    consent_at: Mapped[datetime] = mapped_column(TIMESTAMP, default=utcnow)
    deletion_requested_at: Mapped[datetime | None] = mapped_column(TIMESTAMP)
    deleted_at: Mapped[datetime | None] = mapped_column(TIMESTAMP)
    created_at: Mapped[datetime] = mapped_column(TIMESTAMP, default=utcnow)


class UserEmail(Base):
    """Primary and second emails. An address has one owner across all users.

    primary_user_id is generated by MySQL: user_id for the primary email, NULL
    otherwise. Its unique index allows any number of NULLs, so each user has
    exactly one primary email.
    """

    __tablename__ = "user_emails"
    __table_args__ = (Index("uq_user_emails_primary_user_id", "primary_user_id", unique=True),)

    id: Mapped[int] = mapped_column(ID, primary_key=True)
    user_id: Mapped[int] = mapped_column(ID, ForeignKey("users.id", ondelete="RESTRICT"), index=True)
    email: Mapped[str] = mapped_column(String(254), unique=True)
    is_primary: Mapped[bool] = mapped_column(Boolean, default=False)
    primary_user_id: Mapped[int | None] = mapped_column(
        ID, Computed("CASE WHEN is_primary THEN user_id ELSE NULL END", persisted=True)
    )
    verified_at: Mapped[datetime | None] = mapped_column(TIMESTAMP)
    created_at: Mapped[datetime] = mapped_column(TIMESTAMP, default=utcnow)
